def classify_sentiment_polarity(
    polarity: float,
    threshold: float = 0.15,
) -> SentimentLabel:
    """Classify scalar sentiment polarity in [-1.0, 1.0] into discrete SentimentLabel."""
    if polarity >= threshold:
        return "POSITIVE"
    if polarity <= -threshold:
        return "NEGATIVE"
    return "NEUTRAL"
